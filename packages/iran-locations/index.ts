// and apps/web (cascading province → city selects). A salon's `city` is its county name.
//
// Plain type-strippable TypeScript on purpose (no enums/namespaces): Node loads this file directly,
// like packages/database. Counties are split off every year or two — when one is missing, add it
// to its province here; nothing else needs to change. `center` is the provincial capital, used to
// centre the map picker after a province is chosen.

