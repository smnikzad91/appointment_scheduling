const BY_NAME = new Map(IRAN_PROVINCES.map((p) => [p.name, p]));

/** Arabic ي/ك and stray spaces (common from Windows keyboards and old data) → Persian, trimmed. */
export function normalizePlaceName(value: string): string {
  return value.replace(/ي/g, "ی").replace(/ك/g, "ک").replace(/\s+/g, " ").trim();
}

export function findProvince(name: string): Province | undefined {
  return BY_NAME.get(normalizePlaceName(name));
}

export function citiesOf(province: string): string[] {
  return findProvince(province)?.cities ?? [];
}

/** True when `city` is a county of `province` (both after normalisation). */
export function isCityInProvince(province: string, city: string): boolean {
  return citiesOf(province).includes(normalizePlaceName(city));
}

/**
 * The province a county belongs to — for filling in old salons that only have a city. A few county
 * names repeat across provinces (e.g. «البرز» is also a county of Qazvin); the first match wins.
 */
export function provinceOfCity(city: string): string | undefined {
  const c = normalizePlaceName(city);
  return IRAN_PROVINCES.find((p) => p.cities.includes(c))?.name;
}
