export function tutorialBySlug(slug: string) {
  return TUTORIALS.find((t) => t.slug === slug);
}

/** Previous/next in reading order (owners → stylists → customers). */
export function neighbours(slug: string) {
  const i = TUTORIALS.findIndex((t) => t.slug === slug);
  return { prev: i > 0 ? TUTORIALS[i - 1] : null, next: i >= 0 && i < TUTORIALS.length - 1 ? TUTORIALS[i + 1] : null };
}
